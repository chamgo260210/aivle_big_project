CREATE TABLE marketing_materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL,
    product_service_id BIGINT, material_type VARCHAR(40) NOT NULL, title VARCHAR(200) NOT NULL,
    status VARCHAR(30) NOT NULL, target_persona_segment_id BIGINT, prompt TEXT, content_json TEXT,
    representative_file_id BIGINT UNIQUE,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL, deleted_at TIMESTAMP, version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_material_project FOREIGN KEY (project_id) REFERENCES projects(id),
    CONSTRAINT fk_material_product FOREIGN KEY (product_service_id) REFERENCES product_services(id),

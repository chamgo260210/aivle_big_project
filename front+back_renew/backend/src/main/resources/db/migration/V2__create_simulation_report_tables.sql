CREATE TABLE marketing_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, marketing_material_id BIGINT NOT NULL,
    stored_file_id BIGINT NOT NULL UNIQUE, asset_type VARCHAR(50) NOT NULL,

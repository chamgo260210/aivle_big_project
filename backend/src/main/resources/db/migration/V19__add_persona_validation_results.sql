CREATE TABLE persona_panel_interviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    created_by_user_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    purpose VARCHAR(40) NOT NULL,
    status VARCHAR(20) NOT NULL,
    persona_ids_json TEXT NOT NULL,
    questions_json TEXT NOT NULL,
    answers_json TEXT NOT NULL,
    summary_json TEXT NOT NULL,
    source_snapshot_json TEXT NOT NULL,
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_panel_interview_project FOREIGN KEY (project_id) REFERENCES projects(id),
    CONSTRAINT fk_panel_interview_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id)
);

CREATE INDEX idx_panel_interview_project_updated
    ON persona_panel_interviews(project_id, deleted_at, updated_at);

CREATE TABLE market_response_predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    created_by_user_id BIGINT NOT NULL,
    panel_interview_id BIGINT,
    title VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL,
    persona_ids_json TEXT NOT NULL,
    message_variants_json TEXT NOT NULL,
    price_context VARCHAR(300),
    primary_channel VARCHAR(80),
    result_json TEXT NOT NULL,
    summary_json TEXT NOT NULL,
    source_snapshot_json TEXT NOT NULL,
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_market_response_project FOREIGN KEY (project_id) REFERENCES projects(id),
    CONSTRAINT fk_market_response_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id),
    CONSTRAINT fk_market_response_panel FOREIGN KEY (panel_interview_id) REFERENCES persona_panel_interviews(id)
);

CREATE INDEX idx_market_response_project_updated
    ON market_response_predictions(project_id, deleted_at, updated_at);

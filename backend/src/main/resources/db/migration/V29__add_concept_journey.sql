CREATE TABLE concept_generation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL, idea_version_id BIGINT NOT NULL, task_run_id VARCHAR(64),
    state VARCHAR(20) NOT NULL, result_json TEXT, error VARCHAR(100), completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL, deleted_at TIMESTAMP, version BIGINT NOT NULL,
    CONSTRAINT fk_concept_generation_project FOREIGN KEY (project_id) REFERENCES projects(id),
    CONSTRAINT fk_concept_generation_idea FOREIGN KEY (idea_version_id) REFERENCES idea_versions(id),
    CONSTRAINT fk_concept_generation_task FOREIGN KEY (task_run_id) REFERENCES task_runs(id)
);

CREATE TABLE concepts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL, idea_version_id BIGINT NOT NULL, generation_run_id BIGINT NOT NULL,
    display_order INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL, deleted_at TIMESTAMP, version BIGINT NOT NULL,
    CONSTRAINT fk_concepts_project FOREIGN KEY (project_id) REFERENCES projects(id),
    CONSTRAINT fk_concepts_idea FOREIGN KEY (idea_version_id) REFERENCES idea_versions(id),
    CONSTRAINT fk_concepts_generation FOREIGN KEY (generation_run_id) REFERENCES concept_generation_runs(id),
    CONSTRAINT uk_concepts_generation_order UNIQUE (generation_run_id, display_order)
);

CREATE TABLE concept_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL, idea_version_id BIGINT NOT NULL, concept_id BIGINT NOT NULL,
    version_number INTEGER NOT NULL, name VARCHAR(200) NOT NULL, one_line_summary TEXT NOT NULL,
    target_customer TEXT NOT NULL, problem TEXT NOT NULL, solution TEXT NOT NULL,
    value_proposition TEXT NOT NULL, revenue_model TEXT NOT NULL,
    key_features_json TEXT NOT NULL, differentiators_json TEXT NOT NULL,
    assumptions_json TEXT NOT NULL, risks_json TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL, deleted_at TIMESTAMP, version BIGINT NOT NULL,
    CONSTRAINT fk_concept_versions_project FOREIGN KEY (project_id) REFERENCES projects(id),
    CONSTRAINT fk_concept_versions_idea FOREIGN KEY (idea_version_id) REFERENCES idea_versions(id),
    CONSTRAINT fk_concept_versions_concept FOREIGN KEY (concept_id) REFERENCES concepts(id),
    CONSTRAINT uk_concept_versions_number UNIQUE (concept_id, version_number)
);


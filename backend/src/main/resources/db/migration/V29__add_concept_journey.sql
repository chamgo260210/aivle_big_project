CREATE TABLE quick_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL, idea_version_id BIGINT NOT NULL, run_id BIGINT NOT NULL, concept_version_id BIGINT NOT NULL,
    market_score INTEGER NOT NULL, customer_value_score INTEGER NOT NULL, feasibility_score INTEGER NOT NULL,
    differentiation_score INTEGER NOT NULL, revenue_potential_score INTEGER NOT NULL, legal_risk_score INTEGER NOT NULL,
    overall_score DECIMAL(5,2) NOT NULL, summary TEXT NOT NULL, strengths_json TEXT NOT NULL, weaknesses_json TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL, deleted_at TIMESTAMP, version BIGINT NOT NULL,
    CONSTRAINT fk_quick_project FOREIGN KEY (project_id) REFERENCES projects(id),
    CONSTRAINT fk_quick_idea FOREIGN KEY (idea_version_id) REFERENCES idea_versions(id),
    CONSTRAINT fk_quick_run FOREIGN KEY (run_id) REFERENCES quick_assessment_runs(id),
    CONSTRAINT fk_quick_concept FOREIGN KEY (concept_version_id) REFERENCES concept_versions(id),
    CONSTRAINT uk_quick_run_concept UNIQUE (run_id, concept_version_id)
);

